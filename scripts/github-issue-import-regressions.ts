import "./test-guard";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { eq } from "drizzle-orm";
import { db } from "@factory/storage/client";
import { jobs, repoSettings } from "@factory/storage/schema";
import { fileInternalJob } from "@factory/core/internal-jobs";
import { issueIdentity } from "@factory/core/github-issue-schema";
import { readGithubIssue } from "@factory/runner/github-issue";
import { createJob } from "@factory/core/new-job";
import { newJobDeps } from "@factory/core/new-job-deps";
import { previewGithubIssue, importGithubIssue } from "@factory/core/github-issue-import";
import { startReportServer } from "@factory/runner/report-server";
import { SOURCE_SHAPES } from "@factory/core/sources/shapes";

const repo = `issue-regression/${randomUUID()}`;
const url = `https://github.com/${repo}/issues/3`;
const owner = { email: "issue-owner@example.com", emailVerified: true };
process.env.FACTORY_OWNER_EMAILS = owner.email;
let server: ReturnType<typeof startReportServer> | undefined;
try {
  assert.equal(issueIdentity(url.replace("issue-regression", "ISSUE-REGRESSION")).repo, repo);
  for (const bad of [url.replace("https:", "http:"), url.replace("github.com", "evil.com"), url.replace("issues", "pull"), `${url}?x=1`]) assert.throws(() => issueIdentity(bad));
  await db.insert(repoSettings).values({ repo, registration_status: "ready", updated_at: new Date(), updated_by: "regression" });
  const issue = await readGithubIssue(url, async () => ({ status: 200, json: { title: "Imported title", body: "Original brief", state: "open" } }));
  assert.equal(issue.description, "Original brief");
  await assert.rejects(readGithubIssue(url, async () => ({ status: 200, json: { title: "Closed", body: null, state: "closed" } })), /Only open/);
  await assert.rejects(readGithubIssue(url, async () => ({ status: 200, json: { title: "Pull", body: null, state: "open", pull_request: {} } })), /Pull requests/);
  const input = { requestId: randomUUID(), repo, title: "Edited snapshot title", description: "Edited brief", issueUrl: url };
  const results = await Promise.allSettled([fileInternalJob(db, input, owner.email), fileInternalJob(db, { ...input, requestId: randomUUID() }, owner.email)]);
  assert.equal(results.filter(r => r.status === "fulfilled").length, 1, "concurrent imports cannot create parallel jobs for the same issue");
  const [stored] = await db.select().from(jobs).where(eq(jobs.repo, repo));
  assert.equal(stored!.description, "Edited brief");
  assert.equal(SOURCE_SHAPES.internal.sourceState.parse(stored!.source_state).issueUrl, url);
  const deps = newJobDeps(async () => owner);
  const replay = await importGithubIssue(deps, { requestId: stored!.external_id, url });
  assert.ok(replay.ok, "accepted imports replay without a running runner or open issue");
  await db.update(jobs).set({ stage: "failed" }).where(eq(jobs.repo, repo));
  assert.ok(await fileInternalJob(db, { ...input, requestId: randomUUID() }, owner.email), "a terminal job allows an explicit new import");
  const forbidden = await previewGithubIssue({ ...deps, user: async () => null }, { url });
  assert.equal(forbidden.ok, false);
  const offline = await createJob(deps, { ...input, requestId: randomUUID() });
  assert.equal(offline.ok, false, "runner offline cannot create an imported job");
  server = startReportServer("http://127.0.0.1:0/ingest", "test-only-loopback-secret-32-characters");
  await db.update(jobs).set({ stage: "failed" }).where(eq(jobs.repo, repo));
  const onlineDeps = { ...deps, readIssue: async () => issue };
  const preview = await previewGithubIssue(onlineDeps, { url });
  assert.ok(preview.ok);
  const edited = await createJob(onlineDeps, { ...input, requestId: randomUUID(), description: "Owner edited snapshot" });
  assert.ok(edited.ok);
  const editedRows = await db.select().from(jobs).where(eq(jobs.repo, repo));
  assert.ok(editedRows.some(row => row.description === "Owner edited snapshot"), "submit revalidates without overwriting edited brief");
  await db.update(jobs).set({ stage: "failed" }).where(eq(jobs.repo, repo));
  const imported = await importGithubIssue(onlineDeps, { url, requestId: randomUUID() });
  assert.ok(imported.ok, "CLI import creates a job from the full issue snapshot");
  const unauthorized = await fetch(`http://127.0.0.1:${server.port}/github-issue`, { method: "POST", body: JSON.stringify({ url }) });
  assert.equal(unauthorized.status, 401, "issue lookup requires runner authentication");
  console.log("GitHub issue URL, open-only validation, snapshot persistence, atomic duplicates, replay, offline and authorization regressions passed");
} finally {
  await server?.stop();
  await db.delete(jobs).where(eq(jobs.repo, repo));
  await db.delete(repoSettings).where(eq(repoSettings.repo, repo));
  await db.$client.end();
}
